// Mock bill generator for authentic feel
export function getSimulatedBill(
  providerId: string,
  consumerId: string,
  category: string
): BillLookupDetails {
  const currentMonth = 'October 2026';
  const dueDate = '18 Nov 2026';
  
  if (category === 'electricity') {
    const seed = consumerId.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
    const billAmount = 1450 + (seed % 1900);
    const units = Math.round(billAmount / 7.2);
    return {
      consumerId,
      consumerName: 'Rajesh Sharma',
      providerId,
      billingMonth: currentMonth,
      dueDate,
      billAmount,
      unitsConsumed: units,
      billNumber: `BILL-${Math.abs(seed * 4321).toString().slice(0, 8)}`,
    };
  }

  if (category === 'creditcard') {
    const seed = consumerId.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
    const totalAmount = 8500 + (seed % 28500);
    const minDue = Math.round(totalAmount * 0.05);
    return {
      consumerId,
      consumerName: 'Rajesh Sharma',
      providerId,
      billingMonth: currentMonth,
      dueDate: '15 Nov 2026',
      billAmount: totalAmount,
      minimumDue: minDue,
      billNumber: `STM-${Math.abs(seed * 1111).toString().slice(0, 9)}`,
    };
  }

  return {
    consumerId,
    consumerName: 'Rajesh Sharma',
    providerId,
    billingMonth: currentMonth,
    dueDate,
    billAmount: 399,
    billNumber: `REC-${Date.now().toString().slice(-6)}`,
  };
}

